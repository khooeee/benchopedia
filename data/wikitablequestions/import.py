"""Import the 4,344 WikiTableQuestions test questions from a pinned release commit.

Run from the repository root: python3 data/wikitablequestions/import.py
Only Python's standard library is required. The importer also rewrites
ATTRIBUTION.md, which credits the Wikipedia page behind every table.
"""

import csv
import io
import json
import re
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

BENCHMARK_DIR = Path(__file__).resolve().parent
REPOSITORY = "ppasupat/WikiTableQuestions"
SPLIT_PATH = "data/pristine-unseen-tables.tsv"
SPLIT_FIELDS = ["id", "utterance", "context", "targetValue"]
# Page title and revision for every table in the dataset, not only this split.
METADATA_PATH = "misc/table-metadata.tsv"
METADATA_TABLES = 2108
EXPECTED_COUNT = 4344
EXPECTED_TABLES = 421
ATTRIBUTION_HEADER = """# WikiTableQuestions attribution

The {tables} tables in this snapshot were extracted from these English Wikipedia
pages by Wikipedia contributors and are shared under the [Creative Commons
Attribution-ShareAlike 4.0 International license](https://creativecommons.org/licenses/by-sa/4.0/legalcode).
Each line gives the page title as the upstream metadata records it, a permalink
to the exact revision the table was taken from, and the table file in the pinned
snapshot. Five of these pages have since been deleted from Wikipedia, so their
permalinks no longer resolve; the redistribution review names them.

This file is generated by import.py from the upstream page metadata at commit
`{revision}`.

"""


def fetch(revision, path):
    """Read one upstream file, retrying because this import fetches 400 of them."""
    url = f"https://raw.githubusercontent.com/{REPOSITORY}/{revision}/{path}"
    for attempt in range(4):
        try:
            with urllib.request.urlopen(url, timeout=120) as response:
                return response.read().decode("utf-8")
        except (urllib.error.URLError, TimeoutError):
            if attempt == 3:
                raise
            time.sleep(5 * (attempt + 1))


def unescape(text):
    """Undo the escapes the upstream TSV files use, as the official evaluator does."""
    if re.search(r"\\(?![np\\])", text):
        raise ValueError(f"unsupported escape in {text!r}")
    return text.replace(r"\n", "\n").replace(r"\p", "|").replace("\\\\", "\\")


def table(revision, path):
    """Return the table file verbatim, after checking it parses as a grid."""
    text = fetch(revision, path)
    if "~~~" in text:
        raise ValueError(f"{path}: table cannot be fenced intact")
    # Upstream escapes quotes and backslashes with a backslash instead of doubling.
    grid = list(csv.reader(io.StringIO(text), quotechar='"', escapechar="\\",
                           doublequote=False))
    widths = {len(row) for row in grid}
    if len(grid) < 2 or len(widths) != 1:
        raise ValueError(f"{path}: expected a rectangular table with a header row")
    return text


def pages(revision):
    """Map every table to the Wikipedia page title and revision it was taken from."""
    reader = csv.DictReader(io.StringIO(fetch(revision, METADATA_PATH), newline=""),
                            delimiter="\t", quoting=csv.QUOTE_NONE)
    found = {}
    for row in reader:
        title, page_revision = row["title"], row["pageRev"]
        if not title.strip() or not re.fullmatch(r"\d+", page_revision):
            sys.exit(f"{METADATA_PATH}: missing page title or revision for "
                     f"{row['contextId']}.")
        found[row["contextId"]] = (title, int(page_revision))
    if len(found) != METADATA_TABLES:
        sys.exit(f"{METADATA_PATH}: expected {METADATA_TABLES} tables, found {len(found)}.")
    return found


def to_task(revision, record, line, tables, titles):
    key = record["id"]
    if not re.fullmatch(r"nu-\d+", key):
        raise ValueError(f"{key}: unexpected upstream example ID")
    question = unescape(record["utterance"])
    table_path = record["context"]
    if not re.fullmatch(r"csv/\d+-csv/\d+\.csv", table_path):
        raise ValueError(f"{key}: unexpected table path {table_path!r}")
    answers = [unescape(item) for item in record["targetValue"].split("|")]
    if not question.strip() or not answers or any(not item.strip() for item in answers):
        raise ValueError(f"{key}: empty question or answer")
    title, _ = titles[table_path]
    base = f"https://github.com/{REPOSITORY}/blob/{revision}"
    source = f"{base}/{SPLIT_PATH}#L{line}"
    return {
        "key": key,
        "prompt": f"{question}\n\nWikipedia page: {title}\n\n"
                  f"~~~csv\n{tables[table_path]}\n~~~",
        "solution": "\n".join(answers),
        "prompt_source_url": source,
        "solution_source_url": source,
        "environment_url": f"{base}/{table_path}",
    }


def records(text):
    """Yield each example of the split file with its line number in that file."""
    reader = csv.DictReader(io.StringIO(text, newline=""), delimiter="\t",
                            quoting=csv.QUOTE_NONE)
    if reader.fieldnames != SPLIT_FIELDS:
        sys.exit(f"{SPLIT_PATH}: expected the fields {SPLIT_FIELDS}.")
    for line, record in enumerate(reader, start=2):
        if any(value is None for value in record.values()) or None in record:
            sys.exit(f"{SPLIT_PATH} line {line}: expected {len(SPLIT_FIELDS)} fields.")
        yield line, record


def write_attribution(revision, titles):
    lines = []
    for table_path in sorted(titles):
        title, page_revision = titles[table_path]
        permalink = f"https://en.wikipedia.org/w/index.php?oldid={page_revision}"
        lines.append(f"- [{title}]({permalink}) — `{table_path}`")
    text = ATTRIBUTION_HEADER.format(tables=len(titles), revision=revision)
    (BENCHMARK_DIR / "ATTRIBUTION.md").write_text(text + "\n".join(lines) + "\n",
                                                  encoding="utf-8")


def main():
    benchmark = json.loads((BENCHMARK_DIR / "benchmark.json").read_text(encoding="utf-8"))
    revision = benchmark["dataset_revision"]
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        sys.exit("dataset_revision must be an immutable GitHub commit SHA.")
    if benchmark["task_count"] != EXPECTED_COUNT:
        sys.exit(f"The declared scope must be all {EXPECTED_COUNT} test questions.")
    split = list(records(fetch(revision, SPLIT_PATH)))
    paths = sorted({record["context"] for _, record in split})
    if len(paths) != EXPECTED_TABLES:
        sys.exit(f"Expected {EXPECTED_TABLES} tables, found {len(paths)}.")
    recorded = pages(revision)
    missing = [path for path in paths if path not in recorded]
    if missing:
        sys.exit(f"{METADATA_PATH}: no Wikipedia page recorded for {missing[0]}.")
    titles = {path: recorded[path] for path in paths}
    tables = {path: table(revision, path) for path in paths}
    tasks = [to_task(revision, record, line, tables, titles) for line, record in split]
    tasks.sort(key=lambda task: int(task["key"].split("-")[1]))
    if len(tasks) != EXPECTED_COUNT or len({task["key"] for task in tasks}) != EXPECTED_COUNT:
        sys.exit("WikiTableQuestions count or identifiers differ from the declared scope.")
    out = BENCHMARK_DIR / "tasks.jsonl"
    temporary = out.with_suffix(".jsonl.tmp")
    try:
        with temporary.open("w", encoding="utf-8", newline="\n") as stream:
            for task in tasks:
                stream.write(json.dumps(task, ensure_ascii=False) + "\n")
        temporary.replace(out)
    finally:
        temporary.unlink(missing_ok=True)
    write_attribution(revision, titles)
    print(f"Wrote {len(tasks):,} WikiTableQuestions test questions "
          f"over {len(paths)} tables to {out}")


if __name__ == "__main__":
    main()
