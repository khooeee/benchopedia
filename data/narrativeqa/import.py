"""Import the 10,557 NarrativeQA test questions from a pinned release commit.

Run from the repository root: python3 data/narrativeqa/import.py
Only Python's standard library is required. The importer also rewrites
ATTRIBUTION.md, which credits the Wikipedia page behind every plot summary.
The full stories are not downloaded: every question was written from the
summary, and the summary is what a task prompt gives.
"""

import csv
import io
import json
import re
import sys
import urllib.request
from pathlib import Path

BENCHMARK_DIR = Path(__file__).resolve().parent
REPOSITORY = "google-deepmind/narrativeqa"
DOCUMENTS_PATH = "documents.csv"
QUESTIONS_PATH = "qaps.csv"
SUMMARIES_PATH = "third_party/wikipedia/summaries.csv"
SPLIT = "test"
EXPECTED_COUNT = 10557
EXPECTED_DOCUMENTS = 355
EXPECTED_KINDS = {"movie": 178, "gutenberg": 177}
DOCUMENT_FIELDS = ["document_id", "set", "kind", "story_url", "story_file_size", "wiki_url",
                   "wiki_title", "story_word_count", "story_start", "story_end"]
QUESTION_FIELDS = ["document_id", "set", "question", "answer1", "answer2",
                   "question_tokenized", "answer1_tokenized", "answer2_tokenized"]
SUMMARY_FIELDS = ["document_id", "set", "summary", "summary_tokenized"]
ATTRIBUTION_HEADER = """# NarrativeQA attribution

The {documents} plot summaries in this snapshot were written by contributors to
these English Wikipedia pages and are shared under the [Creative Commons
Attribution-ShareAlike 3.0 Unported license](https://creativecommons.org/licenses/by-sa/3.0/legalcode),
as the upstream `third_party/wikipedia` directory records. Each line gives the
story title and the Wikipedia address upstream records for it, both as the
pinned `documents.csv` writes them. NarrativeQA does not record which revision
each summary came from, so these links point at the page as it stands now, not
as the question's writer read it in 2017.

This file is generated by import.py from the pinned release commit.

"""


def fetch(revision, path):
    """Read one upstream file at the pinned commit."""
    url = f"https://raw.githubusercontent.com/{REPOSITORY}/{revision}/{path}"
    with urllib.request.urlopen(url, timeout=300) as response:
        return response.read().decode("utf-8")


def rows(text, path, fields, flat=False):
    """Yield each row of one upstream file with its line number in that file.

    Pass flat for a file whose line numbers are quoted as sources: it holds no
    newline inside a field, so a row is a line. The summaries do hold newlines.
    """
    if flat and text.count("\n") != len(text.splitlines()):
        sys.exit(f"{path}: expected every row on its own line.")
    reader = csv.DictReader(io.StringIO(text, newline=""))
    if reader.fieldnames != fields:
        sys.exit(f"{path}: expected the fields {fields}.")
    for line, row in enumerate(reader, start=2):
        if any(value is None for value in row.values()) or None in row:
            sys.exit(f"{path} line {line}: expected {len(fields)} fields.")
        yield line, row


def documents(revision):
    """Return the split's stories: document identifier to title and kind."""
    found = {}
    for line, row in rows(fetch(revision, DOCUMENTS_PATH), DOCUMENTS_PATH, DOCUMENT_FIELDS):
        if row["set"] != SPLIT:
            continue
        if not re.fullmatch(r"[0-9a-f]{40}", row["document_id"]):
            sys.exit(f"{DOCUMENTS_PATH} line {line}: unexpected document identifier.")
        if row["kind"] not in EXPECTED_KINDS:
            sys.exit(f"{DOCUMENTS_PATH} line {line}: unexpected kind {row['kind']!r}.")
        for field in ("wiki_title", "wiki_url"):
            if not row[field].strip() or "\n" in row[field]:
                sys.exit(f"{DOCUMENTS_PATH} line {line}: empty or multi-line {field}.")
        found[row["document_id"]] = (row["wiki_title"], row["kind"], row["wiki_url"])
    return found


def summaries(revision, stories):
    """Return each story's plot summary, without its surrounding whitespace."""
    found = {}
    for line, row in rows(fetch(revision, SUMMARIES_PATH), SUMMARIES_PATH, SUMMARY_FIELDS):
        if row["set"] != SPLIT:
            continue
        if row["document_id"] not in stories:
            sys.exit(f"{SUMMARIES_PATH} line {line}: summary for an unknown story.")
        summary = row["summary"].strip()
        if not summary or "~~~" in summary:
            sys.exit(f"{SUMMARIES_PATH} line {line}: empty or unquotable summary.")
        found[row["document_id"]] = summary
    missing = sorted(set(stories) - set(found))
    if missing:
        sys.exit(f"{SUMMARIES_PATH}: no summary for {missing[0]}.")
    return found


def to_task(revision, row, line, index, stories, plots):
    document = row["document_id"]
    if document not in stories:
        raise ValueError(f"{QUESTIONS_PATH} line {line}: question for an unknown story")
    title, kind, _ = stories[document]
    question = row["question"]
    answers = [row["answer1"], row["answer2"]]
    for field in [question, *answers]:
        if not field.strip() or "\n" in field:
            raise ValueError(f"{QUESTIONS_PATH} line {line}: empty or multi-line field")
    source = (f"https://github.com/{REPOSITORY}/blob/{revision}/{QUESTIONS_PATH}#L{line}")
    return {
        "key": f"{document}-{index:02d}",
        "prompt": f"{question}\n\n# Story\n\n- Title: {title}\n- Kind: {kind}\n\n"
                  f"# Wikipedia plot summary\n\n{plots[document]}",
        "solution": "\n".join(answers),
        "prompt_source_url": source,
        "solution_source_url": source,
    }


def write_attribution(stories):
    lines = []
    for document in sorted(stories, key=lambda key: stories[key][0].lower()):
        title, _, url = stories[document]
        lines.append(f"- [{title}]({url})")
    text = ATTRIBUTION_HEADER.format(documents=len(stories))
    (BENCHMARK_DIR / "ATTRIBUTION.md").write_text(text + "\n".join(lines) + "\n",
                                                  encoding="utf-8")


def main():
    benchmark = json.loads((BENCHMARK_DIR / "benchmark.json").read_text(encoding="utf-8"))
    revision = benchmark["dataset_revision"]
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        sys.exit("dataset_revision must be an immutable GitHub commit SHA.")
    if benchmark["task_count"] != EXPECTED_COUNT:
        sys.exit(f"The declared scope must be all {EXPECTED_COUNT} test questions.")
    stories = documents(revision)
    if len(stories) != EXPECTED_DOCUMENTS:
        sys.exit(f"Expected {EXPECTED_DOCUMENTS} stories, found {len(stories)}.")
    kinds = {kind: 0 for kind in EXPECTED_KINDS}
    for _, kind, _ in stories.values():
        kinds[kind] += 1
    if kinds != EXPECTED_KINDS:
        sys.exit(f"Story kinds differ from the declared scope: {kinds}.")
    plots = summaries(revision, stories)
    tasks = []
    asked = {document: 0 for document in stories}
    for line, row in rows(fetch(revision, QUESTIONS_PATH), QUESTIONS_PATH, QUESTION_FIELDS,
                          flat=True):
        if row["set"] != SPLIT:
            continue
        asked[row["document_id"]] += 1
        tasks.append(to_task(revision, row, line, asked[row["document_id"]], stories, plots))
    if len(tasks) != EXPECTED_COUNT or len({task["key"] for task in tasks}) != EXPECTED_COUNT:
        sys.exit(f"Expected {EXPECTED_COUNT} questions, found {len(tasks)}.")
    if min(asked.values()) == 0:
        sys.exit("Every story in the split must carry questions.")
    tasks.sort(key=lambda task: task["key"])
    out = BENCHMARK_DIR / "tasks.jsonl"
    temporary = out.with_suffix(".jsonl.tmp")
    try:
        with temporary.open("w", encoding="utf-8", newline="\n") as stream:
            for task in tasks:
                stream.write(json.dumps(task, ensure_ascii=False) + "\n")
        temporary.replace(out)
    finally:
        temporary.unlink(missing_ok=True)
    write_attribution(stories)
    print(f"Wrote {len(tasks):,} NarrativeQA test questions about "
          f"{len(stories)} stories to {out}")


if __name__ == "__main__":
    main()
