"""Import TabFact's test set: 12,779 statements about 1,695 Wikipedia tables.

Run from the repository root: python3 data/tabfact/import.py
Only Python's standard library is required. Every file is fetched from the
Table-Fact-Checking repository at the commit pinned in benchmark.json, so a rerun
reproduces the same snapshot. The importer also rewrites ATTRIBUTION.md, which
credits the Wikipedia page behind every table where the dataset records it.
"""

import concurrent.futures
import json
import re
import sys
import time
import urllib.error
import urllib.request
from collections import Counter
from pathlib import Path

BENCHMARK_DIR = Path(__file__).resolve().parent
REPOSITORY = "wenhuchen/Table-Fact-Checking"
# The official test split as the README publishes it, lowercased and lemmatized.
STATEMENTS = "tokenized_data/test_examples.json"
TABLE_IDS = "data/test_id.json"
PAGES = "data/table_to_page.json"
TABLES = "data/all_csv"
EXPECTED = 12779
EXPECTED_TABLES = 1695
LABELS = {1: "Entailed", 0: "Refuted"}
# Tables whose page the dataset does not record have the caption "none".
NO_CAPTION = "none"
ATTRIBUTION_HEADER = """# TabFact attribution

The {tables:,} tables in this snapshot were extracted from English Wikipedia pages
by Wikipedia contributors and are shared under the [Creative Commons
Attribution-ShareAlike 4.0 International license](https://creativecommons.org/licenses/by-sa/4.0/legalcode).
Each line gives the table file in the pinned snapshot and the page it was taken
from, with the page title as the dataset records it, in lowercase. The dataset
records no page for {unrecorded} tables, which are listed without one.

This file is generated by import.py from `{pages}` at commit `{revision}`.

"""


def fetch(revision, path):
    """Read one upstream file, retrying because this import fetches 1,700 of them."""
    url = f"https://raw.githubusercontent.com/{REPOSITORY}/{revision}/{path}"
    for attempt in range(4):
        try:
            with urllib.request.urlopen(url, timeout=120) as response:
                return response.read().decode("utf-8")
        except (urllib.error.URLError, TimeoutError):
            if attempt == 3:
                raise
            time.sleep(5 * (attempt + 1))


def table(revision, table_id):
    """Return the table file with its line breaks as LF, after checking it is a grid."""
    text = fetch(revision, f"{TABLES}/{table_id}").replace("\r\n", "\n")
    if "\r" in text or "~~~" in text:
        raise ValueError(f"{table_id}: table cannot be fenced intact")
    rows = text.rstrip("\n").split("\n")
    if len(rows) < 2 or len({len(row.split("#")) for row in rows}) != 1:
        raise ValueError(f"{table_id}: expected a rectangular table with a header row")
    return text.rstrip("\n")


def to_task(revision, table_id, index, statement, label, caption, text):
    if label not in LABELS:
        raise ValueError(f"{table_id}: unexpected label {label!r}")
    if not statement.strip():
        raise ValueError(f"{table_id}: empty statement")
    base = f"https://github.com/{REPOSITORY}/blob/{revision}"
    heading = "" if caption == NO_CAPTION else f"Table caption: {caption}\n\n"
    return {
        "key": f"{table_id.removesuffix('.html.csv')}-{index}",
        "prompt": f"{heading}~~~\n{text}\n~~~\n\nStatement: {statement}\n\n"
                  "Cells in each row of the table are separated by #. "
                  "Is the statement entailed or refuted by the table?",
        "solution": LABELS[label],
        "prompt_source_url": f"{base}/{STATEMENTS}",
        "solution_source_url": f"{base}/{STATEMENTS}",
        "environment_url": f"{base}/{TABLES}/{table_id}",
    }


def write_attribution(revision, table_ids, pages):
    lines = []
    for table_id in sorted(table_ids):
        if table_id in pages:
            title, url = pages[table_id]
            lines.append(f"- `{table_id}`: [{title}]({url})")
        else:
            lines.append(f"- `{table_id}`: page not recorded")
    unrecorded = sum(table_id not in pages for table_id in table_ids)
    text = ATTRIBUTION_HEADER.format(tables=len(table_ids), unrecorded=unrecorded,
                                     pages=PAGES, revision=revision)
    (BENCHMARK_DIR / "ATTRIBUTION.md").write_text(text + "\n".join(lines) + "\n", encoding="utf-8")


def main():
    benchmark = json.loads((BENCHMARK_DIR / "benchmark.json").read_text(encoding="utf-8"))
    revision = benchmark["dataset_revision"]
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        sys.exit("dataset_revision must be a full Git commit SHA.")
    if benchmark["task_count"] != EXPECTED:
        sys.exit(f"The declared scope must be all {EXPECTED:,} test statements.")
    examples = json.loads(fetch(revision, STATEMENTS))
    if set(examples) != set(json.loads(fetch(revision, TABLE_IDS))) or len(examples) != EXPECTED_TABLES:
        sys.exit(f"{STATEMENTS}: tables differ from the {EXPECTED_TABLES:,} in {TABLE_IDS}.")
    pages = {table_id: page for table_id, page in json.loads(fetch(revision, PAGES)).items()
             if table_id in examples}
    for table_id, (statements, labels, caption) in examples.items():
        if not re.fullmatch(r"[12]-\d+-\d+\.html\.csv", table_id):
            sys.exit(f"{table_id}: unexpected table file name.")
        if len(statements) != len(labels) or not statements:
            sys.exit(f"{table_id}: statements and labels do not match.")
        if (caption == NO_CAPTION) != (table_id not in pages):
            sys.exit(f"{table_id}: expected a caption exactly when the page is recorded.")
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        texts = dict(zip(examples, pool.map(lambda table_id: table(revision, table_id), examples)))
    tasks = []
    for table_id in sorted(examples):
        statements, labels, caption = examples[table_id]
        for index, (statement, label) in enumerate(zip(statements, labels)):
            tasks.append(to_task(revision, table_id, index, statement, label, caption, texts[table_id]))
    if len(tasks) != EXPECTED or len({task["key"] for task in tasks}) != EXPECTED:
        sys.exit("TabFact count or keys differ from the declared scope.")
    print(f"Labels: {dict(Counter(task['solution'] for task in tasks))}")
    out = BENCHMARK_DIR / "tasks.jsonl"
    temporary = out.with_suffix(".jsonl.tmp")
    try:
        with temporary.open("w", encoding="utf-8", newline="\n") as stream:
            for task in tasks:
                stream.write(json.dumps(task, ensure_ascii=False) + "\n")
        temporary.replace(out)
    finally:
        temporary.unlink(missing_ok=True)
    write_attribution(revision, examples, pages)
    print(f"Wrote {len(tasks):,} TabFact statements to {out}")


if __name__ == "__main__":
    main()
