"""Import the 7,354 QuAC validation questions from the published split file.

Run from the repository root: python3 data/quac/import.py
Only Python's standard library is required. The importer also rewrites
ATTRIBUTION.md, which credits the Wikipedia article behind every dialogue.
"""

import hashlib
import json
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

BENCHMARK_DIR = Path(__file__).resolve().parent
SPLIT_URL = "https://s3.amazonaws.com/my89public/quac/val_v0.2.json"
EXPECTED_COUNT = 7354
EXPECTED_DIALOGUES = 1000
EXPECTED_ARTICLES = 721
EXPECTED_UNANSWERABLE = 1486
CANNOT_ANSWER = "CANNOTANSWER"
DIALOGUE_FIELDS = ["background", "paragraphs", "section_title", "title"]
PARAGRAPH_FIELDS = ["context", "id", "qas"]
QUESTION_FIELDS = ["answers", "followup", "id", "orig_answer", "question", "yesno"]
# The file stores each dialog act as a single letter; the paper names them.
AFFIRMATION = {"y": "yes", "n": "no", "x": "neither"}
CONTINUATION = {"y": "follow up", "m": "maybe follow up", "n": "don't follow up"}
# Two upstream titles are mangled by an escaping defect; these are the articles
# they stand for, used for the attribution links only.
TITLE_LINKS = {
    'Billy \\Crash\\" Craddock"': 'Billy "Crash" Craddock',
    '\\Weird Al\\" Yankovic"': '"Weird Al" Yankovic',
}
ATTRIBUTION_HEADER = """# QuAC attribution

The article summaries and section text in this snapshot were written by
contributors to these {articles} English Wikipedia articles and are shared under the
[Creative Commons Attribution-ShareAlike 4.0 International license](https://creativecommons.org/licenses/by-sa/4.0/legalcode).
Each line gives the article title as the upstream file records it and a link to
the article. QuAC does not record which revision the text was taken from, so
these links point at the article as it stands now, not as the teacher read it in
2018; 23 of them now redirect to a renamed article. Two titles are mangled
upstream and are linked to the articles they stand for.

This file is generated by import.py from the published validation split.

"""


def fetch(url, checksum):
    """Read one published file and check it is the revision under review."""
    with urllib.request.urlopen(url, timeout=300) as response:
        payload = response.read()
    digest = hashlib.sha256(payload).hexdigest()
    if digest != checksum:
        sys.exit(f"{url} has digest {digest}, not the reviewed {checksum}.")
    return json.loads(payload)


def single_line(label, text):
    """Return one piece of upstream prose, which the prompt layout needs flat."""
    if not text.strip() or "\n" in text:
        raise ValueError(f"empty or multi-line {label}")
    return text


def spans(question, context):
    """Return the recorded answer spans, after checking each against the text."""
    found = []
    for answer in question["answers"]:
        text = answer["text"]
        start = answer["answer_start"]
        if context[start:start + len(text)] != text:
            raise ValueError(f"{question['id']}: answer is not at its recorded offset")
        if not text.strip() or "\n" in text:
            raise ValueError(f"{question['id']}: empty or multi-line answer")
        found.append(text)
    if not found:
        raise ValueError(f"{question['id']}: no reference answer")
    # The official scoring script treats a question whose references are all
    # CANNOTANSWER as having the single reference CANNOTANSWER.
    if all(text == CANNOT_ANSWER for text in found):
        return [CANNOT_ANSWER], True
    if any(text == CANNOT_ANSWER for text in found):
        raise ValueError(f"{question['id']}: CANNOTANSWER mixed with answer spans")
    return found, False


def to_task(dialogue, paragraph, question, history):
    key = question["id"]
    prefix, _, index = key.rpartition("_q#")
    if prefix != paragraph["id"] or not re.fullmatch(r"\d+", index):
        raise ValueError(f"{key}: unexpected question identifier")
    text = question["question"]
    if not text.strip() or "\n" in text:
        raise ValueError(f"{key}: empty or multi-line question")
    if question["yesno"] not in AFFIRMATION or question["followup"] not in CONTINUATION:
        raise ValueError(f"{key}: unexpected dialog act")
    answers, _ = spans(question, paragraph["context"])
    turns = "\n".join(f"Student: {asked}\nTeacher: {answered}"
                      for asked, answered in history)
    prompt = [text]
    if history:
        prompt.append(f"# Conversation so far\n\n{turns}")
    prompt.append(f"# Source\n\n- Article: {single_line('title', dialogue['title'])}\n"
                  f"- Section: {single_line('section title', dialogue['section_title'])}")
    prompt.append(f"# Article summary\n\n{single_line('summary', dialogue['background'])}")
    prompt.append(f"# Section text\n\n{single_line('section text', paragraph['context'])}")
    solution = "\n".join(answers) + (
        f"\n\nAffirmation: {AFFIRMATION[question['yesno']]}"
        f"\nContinuation: {CONTINUATION[question['followup']]}")
    return {
        "key": key,
        "prompt": "\n\n".join(prompt),
        "solution": solution,
        "prompt_source_url": SPLIT_URL,
        "solution_source_url": SPLIT_URL,
    }


def dialogues(payload):
    """Yield every dialogue of the split, after checking its shape."""
    if sorted(payload) != ["data"]:
        sys.exit("The split file must hold the dialogues under a single data key.")
    for dialogue in payload["data"]:
        if sorted(dialogue) != DIALOGUE_FIELDS:
            sys.exit(f"Expected the dialogue fields {DIALOGUE_FIELDS}.")
        if len(dialogue["paragraphs"]) != 1:
            sys.exit(f"{dialogue['title']}: expected one section per dialogue.")
        paragraph = dialogue["paragraphs"][0]
        if sorted(paragraph) != PARAGRAPH_FIELDS:
            sys.exit(f"Expected the section fields {PARAGRAPH_FIELDS}.")
        if not paragraph["context"].endswith(CANNOT_ANSWER):
            sys.exit(f"{paragraph['id']}: section text must end with {CANNOT_ANSWER}.")
        for field in ("title", "section_title", "background"):
            if not dialogue[field].strip():
                sys.exit(f"{paragraph['id']}: empty {field}.")
        for question in paragraph["qas"]:
            if sorted(question) != QUESTION_FIELDS:
                sys.exit(f"Expected the question fields {QUESTION_FIELDS}.")
        yield dialogue, paragraph


def tasks_of(dialogue, paragraph):
    """Yield the dialogue's questions in order, each with the turns before it.

    Question numbers count from zero within a dialogue but need not be
    consecutive: one dialogue of this split skips a number.
    """
    history = []
    previous = -1
    for question in paragraph["qas"]:
        index = int(question["id"].rpartition("_q#")[2])
        if index <= previous:
            raise ValueError(f"{question['id']}: questions are out of order")
        previous = index
        yield to_task(dialogue, paragraph, question, history)
        original = question["orig_answer"]["text"]
        if original not in [answer["text"] for answer in question["answers"]]:
            raise ValueError(f"{question['id']}: original answer is not a reference")
        history.append((question["question"], original))


def write_attribution(titles):
    lines = []
    for title in sorted(titles):
        article = TITLE_LINKS.get(title, title)
        path = urllib.parse.quote(article.replace(" ", "_"), safe="_,()'!:.-")
        lines.append(f"- [{title}](https://en.wikipedia.org/wiki/{path})")
    text = ATTRIBUTION_HEADER.format(articles=len(titles))
    (BENCHMARK_DIR / "ATTRIBUTION.md").write_text(text + "\n".join(lines) + "\n",
                                                  encoding="utf-8")


def main():
    benchmark = json.loads((BENCHMARK_DIR / "benchmark.json").read_text(encoding="utf-8"))
    revision = benchmark["dataset_revision"]
    if not re.fullmatch(r"[0-9a-f]{64}", revision):
        sys.exit("dataset_revision must be the SHA-256 digest of the split file.")
    if benchmark["task_count"] != EXPECTED_COUNT:
        sys.exit(f"The declared scope must be all {EXPECTED_COUNT} validation questions.")
    split = list(dialogues(fetch(SPLIT_URL, revision)))
    if len(split) != EXPECTED_DIALOGUES:
        sys.exit(f"Expected {EXPECTED_DIALOGUES} dialogues, found {len(split)}.")
    titles = {dialogue["title"] for dialogue, _ in split}
    if len(titles) != EXPECTED_ARTICLES:
        sys.exit(f"Expected {EXPECTED_ARTICLES} articles, found {len(titles)}.")
    tasks = [task for dialogue, paragraph in split
             for task in tasks_of(dialogue, paragraph)]
    unanswerable = sum(task["solution"].startswith(f"{CANNOT_ANSWER}\n\n") for task in tasks)
    if unanswerable != EXPECTED_UNANSWERABLE:
        sys.exit(f"Expected {EXPECTED_UNANSWERABLE} unanswerable questions, "
                 f"found {unanswerable}.")
    tasks.sort(key=lambda task: (task["key"].split("_q#")[0],
                                 int(task["key"].split("_q#")[1])))
    if len(tasks) != EXPECTED_COUNT or len({task["key"] for task in tasks}) != EXPECTED_COUNT:
        sys.exit("QuAC count or identifiers differ from the declared scope.")
    out = BENCHMARK_DIR / "tasks.jsonl"
    temporary = out.with_suffix(".jsonl.tmp")
    try:
        with temporary.open("w", encoding="utf-8", newline="\n") as stream:
            for task in tasks:
                stream.write(json.dumps(task, ensure_ascii=False) + "\n")
        temporary.replace(out)
    finally:
        temporary.unlink(missing_ok=True)
    write_attribution(titles)
    print(f"Wrote {len(tasks):,} QuAC validation questions over "
          f"{len(split):,} dialogues to {out}")


if __name__ == "__main__":
    main()
